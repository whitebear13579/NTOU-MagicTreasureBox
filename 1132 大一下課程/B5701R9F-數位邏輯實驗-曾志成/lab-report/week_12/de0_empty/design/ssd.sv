module ssd(
    input  logic [3:0] a,
    output logic [6:0] seg   
);

  assign seg[0] = ~(
       (a[1] & a[2])
     | (a[1] & ~a[3])
     | (a[3] & ~a[0])
     | (~a[0] & ~a[2])
     | (a[0] & a[2] & ~a[3])
     | (a[3] & ~a[1] & ~a[2])
  );

  assign seg[1] = ~(
       (~a[0] & ~a[2])
     | (~a[2] & ~a[3])
     | (a[0] & a[1] & ~a[3])
     | (a[0] & a[3] & ~a[1])
     | (~a[0] & ~a[1] & ~a[3])
  );

  assign seg[2] = ~(
       (a[0] & ~a[1])
     | (a[0] & ~a[3])
     | (a[2] & ~a[3])
     | (a[3] & ~a[2])
     | (~a[1] & ~a[3])
  );

  assign seg[3] = ~(
       (a[3] & ~a[1])
     | (a[0] & a[1] & ~a[2])
     | (a[0] & a[2] & ~a[1])
     | (a[0] & a[3] & ~a[2])
     | (a[1] & a[2] & ~a[0])
     | (a[2] & a[3] & ~a[0])
     | (a[1] & ~a[0] & ~a[3])
     | (a[1] & ~a[2] & ~a[3])
     | (~a[0] & ~a[1] & ~a[2])
     | (~a[0] & ~a[2] & ~a[3])
  );

  assign seg[4] = ~(
       (a[1] & a[3])
     | (a[2] & a[3])
     | (a[1] & ~a[0])
     | (~a[0] & ~a[2])
  );

  assign seg[5] = ~(
       (a[1] & a[3])
     | (a[2] & ~a[0])
     | (a[3] & ~a[2])
     | (~a[0] & ~a[1])
     | (a[2] & ~a[1] & ~a[3])
  );

  assign seg[6] = ~(
       (a[0] & a[3])
     | (a[1] & a[3])
     | (a[1] & ~a[0])
     | (a[1] & ~a[2])
     | (a[3] & ~a[2])
     | (a[0] & a[2] & ~a[1])
     | (a[2] & ~a[0] & ~a[3])
     | (a[2] & ~a[1] & ~a[3])
  );

endmodule
